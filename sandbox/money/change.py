"""Сдача: сколько вернуть покупателю в копейках; оплачено столько же или меньше — 0;
отрицательные входы — ошибка. Оба правила — по условию тикета #18 (возврат здесь не
считается, недоплату считает `shortfall_kop`)."""


def change_kop(paid_kop: int, due_kop: int) -> int:
    if paid_kop < 0 or due_kop < 0:
        raise ValueError("сумма не может быть отрицательной")
    return max(paid_kop - due_kop, 0)
